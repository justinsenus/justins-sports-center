import {strict as assert} from 'node:assert';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const context={window:{},Date,Map,localStorage:{getItem:()=>null,setItem(){}}};
vm.runInNewContext(await readFile(new URL('../chart-timeline.js',import.meta.url),'utf8'),context);
const t=context.window.FantasyTimeline;
const at=s=>Date.parse('2026-10-'+s+'Z');
const history=[{at:'2026-10-02T00:00:00Z',values:[0,0]},{at:'2026-10-02T03:00:00Z',values:[20,30]},{at:'2026-10-04T17:00:00Z',values:[21,29]},{at:'2026-10-04T18:00:00Z',values:[40,50]}];
assert.deepEqual(Array.from(t.mapIndex(history),p=>p.index),[0,1,2,3]);
assert.equal(t.select(history)[2].values[1],29,'Negative score corrections stay in sequence');
const windows=[[at('02T00:00:00'),at('02T03:00:00')],[at('04T17:00:00'),at('04T18:00:00')],[at('06T00:00:00'),at('06T02:00:00')]];
assert.equal(t.activeTime(at('04T16:00:00'),windows),3*3600000,'Friday and Saturday contribute no execution time');
const selected=t.rolling(history,windows,at('04T18:00:00'));
assert.equal(selected.length,3);assert.ok(selected[0].windowAnchor,'Rolling view carries the prior total rather than resetting scores to zero');
assert.equal(t.rolling(history,[],Date.now()).length,1,'Missing execution history does not masquerade as a live hour');
const live=[{status:{type:{state:'in',completed:false}}}];
t.observe('sleeper:5',live,100000);t.observe('sleeper:5',live,105000);t.observe('sleeper:5',[],110000);
const observed=t.observe('sleeper:5',[],999999);
assert.equal(t.activeTime(999999,observed),10000,'Inactive gaps are excluded');
console.log('Passed: sequential compressed indexes, retained corrections, dead-zone skipping, active execution hour, carried totals, and unknown-history handling.');
