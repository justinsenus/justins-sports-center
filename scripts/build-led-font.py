ALIASES = {"’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", "—": "-", "•": "·", "−": "-"}


def glyph(pattern):
    pen = TTGlyphPen(None)
    radius = 34
    for row, line in enumerate(pattern.split("/")):
        for column, bit in enumerate(line):
            if bit != "1":
                continue
            x, y = 80 + 100 * column, 700 - 100 * row
            pen.moveTo((x + radius, y))
            pen.qCurveTo((x + radius, y - radius), (x, y - radius))
            pen.qCurveTo((x - radius, y - radius), (x - radius, y))
            pen.qCurveTo((x - radius, y + radius), (x, y + radius))
            pen.qCurveTo((x + radius, y + radius), (x + radius, y))
            pen.closePath()
    return pen.glyph()


def main():
    destination = Path(__file__).resolve().parents[1] / "remote" / "fonts" / "scoreboard-led.woff"
    destination.parent.mkdir(parents=True, exist_ok=True)
    font = FontBuilder(1000, isTTF=True)
    names = {character: "uni%04X" % ord(character) for character in PATTERNS}
    order = [".notdef"] + list(names.values())
    font.setupGlyphOrder(order)
    font.setupCharacterMap({**{ord(c): n for c, n in names.items()}, **{ord(c): names[target] for c, target in ALIASES.items()}})
    font.setupGlyf({".notdef": glyph(PATTERNS["?"]), **{names[c]: glyph(pattern) for c, pattern in PATTERNS.items()}})
    font.setupHorizontalMetrics({name: (620, 46) for name in order})
    font.setupHorizontalHeader(ascent=850, descent=-150)
    font.setupNameTable({"familyName": "Justin Scoreboard LED", "styleName": "Regular", "uniqueFontIdentifier": "JustinScoreboardLED-1.0", "fullName": "Justin Scoreboard LED", "psName": "JustinScoreboardLED", "version": "Version 1.0", "copyright": "Original glyph designs. Dedicated to the public domain under CC0-1.0."})
    font.setupOS2(sTypoAscender=850, sTypoDescender=-150, usWinAscent=850, usWinDescent=150, sCapHeight=734, sxHeight=534)
    font.setupPost()
    font.setupMaxp()
    font.font.flavor = "woff"
    font.font.recalcTimestamp = False
    font.font["head"].created = font.font["head"].modified = 3874608000
    font.save(destination)
    print(destination)


if __name__ == "__main__":
    main()
